// Builds LazySpec for Claude.
//   node build.js         dist/server.js: one file (the Claude Code plugin runs it, from this repository)
//   node build.js --pack  also lazyspec.mcpb: the Claude Desktop extension (server, exporter, OpenSpec CLI)
// The version is desktop/package.json's; the manifest's tool and prompt lists are asked from the server itself.

const cp = require('child_process');
const fs = require('fs');
const path = require('path');
const esbuild = require('esbuild');

const here = __dirname;
const repo = path.join(here, '..');
const pkg = JSON.parse(fs.readFileSync(path.join(here, 'package.json'), 'utf8'));
const version = pkg.version;

// 1. The server, bundled with LazySpec's model and ops (vscode/src).
esbuild.buildSync({
  entryPoints: [path.join(here, 'src', 'server.ts')],
  bundle: true, platform: 'node', target: 'node18', format: 'cjs',
  outfile: path.join(here, 'dist', 'server.js'),
  define: { LAZYSPEC_VERSION: JSON.stringify(version) },
  banner: { js: `// LazySpec ${version} for Claude - generated by desktop/build.js from desktop/src and vscode/src; do not edit.` },
  logLevel: 'warning',
});
console.log(`dist/server.js (${version})`);

// The plugin's version follows (Claude Code reads it from .claude-plugin/plugin.json).
const pluginFile = path.join(repo, '.claude-plugin', 'plugin.json');
if (fs.existsSync(pluginFile)) {
  const plugin = JSON.parse(fs.readFileSync(pluginFile, 'utf8'));
  if (plugin.version !== version) { plugin.version = version; fs.writeFileSync(pluginFile, JSON.stringify(plugin, null, 2) + '\n'); console.log(`.claude-plugin/plugin.json: ${version}`); }
}

if (!process.argv.includes('--pack')) { return; }

// 2. What the server offers, from the server (initialize, tools/list, prompts/list).
function ask(server) {
  const input = [
    { jsonrpc: '2.0', id: 1, method: 'initialize', params: { protocolVersion: '2025-06-18', capabilities: {}, clientInfo: { name: 'build', version } } },
    { jsonrpc: '2.0', id: 2, method: 'tools/list' },
    { jsonrpc: '2.0', id: 3, method: 'prompts/list' },
  ].map(m => JSON.stringify(m)).join('\n') + '\n';
  const r = cp.spawnSync(process.execPath, [server, here], { input, encoding: 'utf8' });
  const byId = Object.fromEntries(r.stdout.split('\n').filter(Boolean).map(l => JSON.parse(l)).map(m => [m.id, m.result]));
  return { tools: byId[2].tools, prompts: byId[3].prompts };
}
const offered = ask(path.join(here, 'dist', 'server.js'));

// 3. The extension's folder: manifest, icon, licence, server, the exporter (tools/lazyspec), the OpenSpec CLI.
const stage = path.join(here, 'build');
fs.rmSync(stage, { recursive: true, force: true });
fs.mkdirSync(path.join(stage, 'server', 'kit'), { recursive: true });
const manifest = JSON.parse(fs.readFileSync(path.join(here, 'manifest.json'), 'utf8'));
manifest.version = version;
manifest.tools = offered.tools.map(t => ({ name: t.name, description: t.description.split('. ')[0].replace(/\.$/, '') + '.' }));
manifest.prompts = offered.prompts.map(p => ({ name: p.name, description: p.description, arguments: p.arguments.map(a => a.name), text: `Use LazySpec's ${p.name} prompt.` }));
fs.writeFileSync(path.join(stage, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
fs.copyFileSync(path.join(repo, 'vscode', 'media', 'icon.png'), path.join(stage, 'icon.png'));
fs.copyFileSync(path.join(repo, 'LICENSE'), path.join(stage, 'LICENSE'));
fs.copyFileSync(path.join(here, 'dist', 'server.js'), path.join(stage, 'server', 'server.js'));
for (const f of ['lazyspec.ps1', 'export-texts.json', 'kit.json', 'LAZYSPEC.md']) {
  fs.copyFileSync(path.join(repo, 'tools', 'lazyspec', f), path.join(stage, 'server', 'kit', f));
}
// The Netmedia plugins' tools that run_tool runs in Claude Desktop Chat, where the installed plugins' files can't be
// reached: copied from AIToolbelt (NETMEDIA_AITOOLBELT, else the clone next to this repository) - a generated copy,
// never edited here. Without AIToolbelt the extension is packed without them and run_tool says so.
const NETMEDIA_BUNDLE = {
  netmedia: ['skills/prepare-offer/scripts', 'skills/estimate/scripts', 'skills/estimate/assets'],
  'netmedia-tools': ['skills/translate/scripts', 'skills/hasek/scripts'],
  'netmedia-document': ['scripts', 'theme', 'offer'],
};
const toolbelt = process.env.NETMEDIA_AITOOLBELT || path.join(repo, '..', 'AIToolbelt');
if (fs.existsSync(path.join(toolbelt, 'plugins'))) {
  const skip = (src) => /(__pycache__|node_modules|[._]test\.(py|ts|js)$)/.test(src.replace(/\\/g, '/'));
  for (const [plugin, folders] of Object.entries(NETMEDIA_BUNDLE)) {
    for (const folder of folders) {
      const from = path.join(toolbelt, 'plugins', plugin, folder);
      if (!fs.existsSync(from)) { console.error(`AIToolbelt has no plugins/${plugin}/${folder}`); process.exit(1); }
      fs.cpSync(from, path.join(stage, 'server', 'netmedia', plugin, folder), { recursive: true, filter: (src) => !skip(src) });
    }
  }
  const head = cp.spawnSync('git', ['rev-parse', '--short', 'HEAD'], { cwd: toolbelt, encoding: 'utf8' }).stdout.trim();
  fs.writeFileSync(path.join(stage, 'server', 'netmedia', 'SOURCE.txt'), `Copied from AIToolbelt ${head || '(unknown commit)'} by desktop/build.js; do not edit.\n`);
  console.log(`netmedia tools: AIToolbelt ${head || toolbelt}`);
} else {
  console.warn(`! AIToolbelt not found (${toolbelt}): packed without the Netmedia tools; run_tool needs the installed plugins.`);
}

const openspecVersion = pkg.dependencies['@fission-ai/openspec'];
fs.writeFileSync(path.join(stage, 'server', 'package.json'), JSON.stringify({ name: 'lazyspec-server', private: true, version, dependencies: { '@fission-ai/openspec': openspecVersion } }, null, 2));
const npm = process.platform === 'win32' ? 'npm.cmd' : 'npm';
const inst = cp.spawnSync(npm, ['install', '--omit=dev', '--no-audit', '--no-fund', '--no-package-lock'], { cwd: path.join(stage, 'server'), stdio: 'inherit', shell: process.platform === 'win32' });
if (inst.status !== 0) { console.error('npm install of the OpenSpec CLI failed'); process.exit(1); }

// 4. Validated and packed.
const mcpb = path.join(here, 'node_modules', '@anthropic-ai', 'mcpb', 'dist', 'cli', 'cli.js');
const out = path.join(here, 'lazyspec.mcpb');
for (const args of [['validate', path.join(stage, 'manifest.json')], ['pack', stage, out]]) {
  const r = cp.spawnSync(process.execPath, [mcpb, ...args], { stdio: 'inherit' });
  if (r.status !== 0) { console.error(`mcpb ${args[0]} failed`); process.exit(1); }
}
console.log(`lazyspec.mcpb (${version}): ${(fs.statSync(out).size / 1048576).toFixed(1)} MB`);
